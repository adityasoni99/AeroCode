"""Evidence Report Generator: Compiles cryptographically auditable JSON and Markdown reports."""

import json
from typing import List, Optional

from aero_code.schemas.patch import PatchProposal
from aero_code.schemas.report import EvidenceReport, VerificationVerdict
from aero_code.schemas.research import TavilyCitation


class EvidenceReportGenerator:
    """Formats verification proofs into auditable JSON and GitHub PR Markdown summaries."""

    def generate(
        self,
        run_id: str,
        repository: str = "",
        baseline_commit: str = "",
        patch_commit: str = "",
        model_used: str = "nvidia/Nemotron-3.5-Lightning",
        citations: Optional[List[TavilyCitation]] = None,
        patch: Optional[PatchProposal] = None,
        baseline_test_passed: bool = False,
        patched_test_passed: bool = False,
        baseline_suite_passed: bool = False,
        git_guard_passed: bool = False,
        verdict: VerificationVerdict = VerificationVerdict.VERIFIED,
        execution_duration_ms: float = 0.0,
        notes: str = "",
    ) -> EvidenceReport:
        """Create structured EvidenceReport model."""
        return EvidenceReport(
            run_id=run_id,
            repository=repository,
            baseline_commit=baseline_commit,
            patch_commit=patch_commit,
            model_used=model_used,
            citations=citations or [],
            patch=patch,
            baseline_test_passed=baseline_test_passed,
            patched_test_passed=patched_test_passed,
            baseline_suite_passed=baseline_suite_passed,
            git_guard_passed=git_guard_passed,
            verdict=verdict,
            execution_duration_ms=execution_duration_ms,
            notes=notes,
        )

    def to_markdown(self, report: EvidenceReport) -> str:
        """Render report as a GitHub Pull Request description."""
        status_badge = "✅ **VERIFIED**" if report.verdict == VerificationVerdict.VERIFIED else f"⚠️ **{report.verdict.value}**"

        lines = [
            "# 🛡️ Aero-Code (ProofLoop) Verification Evidence Report",
            "",
            f"**Run ID:** `{report.run_id}` | **Status:** {status_badge} | **Model:** `{report.model_used}`",
            "",
            "## Double-Verification Matrix",
            "",
            "| Verification Check | Required Outcome | Actual Outcome | Status |",
            "| :--- | :--- | :--- | :--- |",
            f"| **Bug Reproduction** | Regression test FAILS on baseline | {'FAILED (Reproduction Confirmed)' if not report.baseline_test_passed else 'PASSED (Failed to repro)'} | {'✅' if not report.baseline_test_passed else '❌'} |",
            f"| **Bug Resolution** | Regression test PASSES on patch | {'PASSED' if report.patched_test_passed else 'FAILED'} | {'✅' if report.patched_test_passed else '❌'} |",
            f"| **Zero Regressions** | 100% baseline tests pass | {'ALL PASS' if report.baseline_suite_passed else 'REGRESSION'} | {'✅' if report.baseline_suite_passed else '❌'} |",
            f"| **Git Guard Policy** | Baseline tests & configs immutable | {'IMMUTABLE' if report.git_guard_passed else 'VIOLATION'} | {'✅' if report.git_guard_passed else '❌'} |",
            "",
            f"**Overall Verdict:** `{report.verdict.value}`",
            "",
        ]

        if report.citations:
            lines.extend([
                "## Tavily Research Citations",
                "",
                "The patch was synthesized using documentation retrieved dynamically via Tavily Search:",
                "",
            ])
            for i, citation in enumerate(report.citations, 1):
                lines.append(f"{i}. [{citation.title}]({citation.url})")
                lines.append(f"   > *\"{citation.snippet.strip()}\"*")
                lines.append("")

        if report.patch:
            lines.extend([
                "## Patch Summary",
                "",
                report.patch.explanation or "Surgical bug repair generated by NVIDIA Nemotron.",
                "",
            ])
            for diff in report.patch.diffs:
                lines.extend([
                    f"### `{diff.file_path}`",
                    "```diff",
                    f"--- a/{diff.file_path}",
                    f"+++ b/{diff.file_path}",
                    f"- {diff.old_content.strip()}",
                    f"+ {diff.new_content.strip()}",
                    "```",
                    "",
                ])

        lines.extend([
            "---",
            "*Generated deterministically by [Aero-Code](https://github.com/aero-code/aero-code) via ProofLoop verification engine.*",
        ])

        return "\n".join(lines)
